"""AST linter that forbids hardcoded layout coordinates and instance-specific net heuristics.

Physical layout, routing, and untangling algorithms must operate purely on
geometry, graph topology, and relative clearance channels.
Hardcoding absolute coordinates (e.g. x=179500, y=674500) or instance-specific
net names (e.g. matching '__u_') is strictly prohibited.
"""

from __future__ import annotations

import ast
import re
from pathlib import Path

# Absolute coordinates in DEF are multiples of 500 or 1000 and exceed standard macro dimensions.
# Standard macro sizes in DEF units are <= 9000 (for example 7000 for 7x7 oil refinery).
MAX_ALLOWED_RELATIVE_OFFSET = 9000

# Pattern identifying instance-specific net names generated by synthesis (for example net__u_instance_num)
INSTANCE_NET_PATTERN = re.compile(r"__u_[a-zA-Z0-9_]+")

EXCLUDED_FILES = frozenset(
    {
        "pdk.py",
        "solve.py",
        "make_fixture.py",
    }
)


class HardcodedRoutingVisitor(ast.NodeVisitor):
    """AST visitor that detects hardcoded layout coordinates and instance-specific net heuristics."""

    def __init__(self, filename: str) -> None:
        self.filename = filename
        self.violations: list[str] = []

    def _check_large_number(self, node: ast.AST, val: int | float) -> None:
        # Ignore boolean True/False (which are ints in Python AST)
        if isinstance(val, bool):
            return
        if abs(val) > MAX_ALLOWED_RELATIVE_OFFSET:
            line = getattr(node, "lineno", 0)
            self.violations.append(
                f"{self.filename}:{line}: Forbidden hardcoded layout coordinate: {val}. "
                f"Layout and untangling algorithms must not use absolute coordinates."
            )

    def _check_net_string(self, node: ast.AST, val: str) -> None:
        if INSTANCE_NET_PATTERN.search(val):
            line = getattr(node, "lineno", 0)
            self.violations.append(
                f"{self.filename}:{line}: Forbidden instance-specific net match: '{val}'. "
                f"Layout and untangling algorithms must be net-agnostic."
            )

    def visit_Compare(self, node: ast.Compare) -> None:
        # Inspect left and comparators
        all_exprs = [node.left, *node.comparators]
        for expr in all_exprs:
            if isinstance(expr, ast.Constant):
                if isinstance(expr.value, (int, float)):
                    self._check_large_number(expr, expr.value)
                elif isinstance(expr.value, str):
                    self._check_net_string(expr, expr.value)
            elif isinstance(expr, (ast.Tuple, ast.List, ast.Set)):
                for elt in expr.elts:
                    if isinstance(elt, ast.Constant):
                        if isinstance(elt.value, (int, float)):
                            self._check_large_number(elt, elt.value)
                        elif isinstance(elt.value, str):
                            self._check_net_string(elt, elt.value)
        self.generic_visit(node)

    def visit_Dict(self, node: ast.Dict) -> None:
        # Inspect dict values for hardcoded wire geometries like {"x1": 179500, "y1": 674500}
        for k, v in zip(node.keys, node.values, strict=True):
            if (
                isinstance(k, ast.Constant)
                and k.value in ("x", "y", "x1", "y1", "x2", "y2")
                and isinstance(v, ast.Constant)
                and isinstance(v.value, (int, float))
            ):
                self._check_large_number(v, v.value)
        self.generic_visit(node)

    def visit_Assign(self, node: ast.Assign) -> None:
        if isinstance(node.value, ast.Constant):
            if isinstance(node.value.value, (int, float)):
                self._check_large_number(node.value, node.value.value)
            elif isinstance(node.value.value, str):
                self._check_net_string(node.value, node.value.value)
        self.generic_visit(node)


def check_file(path: Path) -> list[str]:
    """Check a single Python file for hardcoded routing constructs."""
    if path.name.startswith("test_") or path.name in EXCLUDED_FILES:
        return []
    try:
        content = path.read_text(encoding="utf-8")
        tree = ast.parse(content, filename=str(path))
    except Exception as exc:
        return [f"{path}: Failed to parse AST: {exc}"]

    visitor = HardcodedRoutingVisitor(str(path))
    visitor.visit(tree)
    return visitor.violations


def check_directory(dir_path: Path) -> list[str]:
    """Check all Python files in a directory."""
    violations: list[str] = []
    for path in sorted(dir_path.rglob("*.py")):
        violations.extend(check_file(path))
    return violations


def main() -> int:
    """CLI entry point for AST linter."""
    import sys

    target_path = Path("foundry") if len(sys.argv) < 2 else Path(sys.argv[1])
    violations = check_file(target_path) if target_path.is_file() else check_directory(target_path)
    if violations:
        for v in violations:
            sys.stderr.write(f"{v}\n")
        sys.stderr.write(f"\nFound {len(violations)} forbidden hardcoded routing construct(s).\n")
        return 1
    return 0


if __name__ == "__main__":
    import sys

    sys.exit(main())
